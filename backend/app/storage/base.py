"""Storage for original uploaded files.

Keys are generated by our code (never from user input), e.g. `documents/<uuid>/original.pdf`.
"""

from typing import Protocol


class StorageError(Exception):
    """The storage backend failed (unreachable, rejected the request, ...)."""


class ObjectNotFoundError(StorageError):
    pass


class Storage(Protocol):
    async def put(self, key: str, data: bytes, content_type: str) -> None: ...

    async def get(self, key: str) -> bytes: ...

    async def delete(self, key: str) -> None:
        """Delete the object. Deleting a missing object is not an error."""
        ...


def document_key(document_id: str, file_type: str) -> str:
    return f"documents/{document_id}/original.{file_type}"
