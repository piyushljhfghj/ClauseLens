"""Resolve Word automatic numbering ("8.2", "Article IV", "(a)") into the text a reader sees.

In a .docx, clause numbers are usually not in the paragraph text: they are generated by Word
from `numbering.xml` (w:abstractNum level definitions) and the paragraph's (or its style's)
w:numPr. Without this, "Section 8.2" would not exist anywhere in our extracted text.

Supported: per-level start values, number formats (decimal, letters, roman), multi-level text
templates ("%1.%2."), level restarts, w:num start overrides, numbering inherited from styles.
Not supported (rare in contracts): legal-style isLgl conversion, custom ordinal text formats.
"""

from dataclasses import dataclass, field

from docx.document import Document as DocxDocument
from docx.oxml.ns import qn

MAX_LEVELS = 9


@dataclass
class _Level:
    start: int = 1
    fmt: str = "decimal"
    text: str = "%1."


@dataclass
class _Abstract:
    levels: dict[int, _Level] = field(default_factory=dict)


def _int_attr(element, name: str) -> int | None:  # type: ignore[no-untyped-def]
    if element is None:
        return None
    value = element.get(qn(name))
    try:
        return int(value) if value is not None else None
    except ValueError:
        return None


def _to_letters(n: int, upper: bool) -> str:
    # Word: a..z, then aa..zz, aaa..
    letter = chr(ord("a") + (n - 1) % 26)
    text = letter * ((n - 1) // 26 + 1)
    return text.upper() if upper else text


def _to_roman(n: int, upper: bool) -> str:
    numerals = [
        (1000, "m"), (900, "cm"), (500, "d"), (400, "cd"), (100, "c"), (90, "xc"),
        (50, "l"), (40, "xl"), (10, "x"), (9, "ix"), (5, "v"), (4, "iv"), (1, "i"),
    ]  # fmt: skip
    out = []
    for value, symbol in numerals:
        while n >= value:
            out.append(symbol)
            n -= value
    text = "".join(out)
    return text.upper() if upper else text


def format_number(n: int, fmt: str) -> str:
    if n <= 0:
        return str(n)
    match fmt:
        case "lowerLetter":
            return _to_letters(n, upper=False)
        case "upperLetter":
            return _to_letters(n, upper=True)
        case "lowerRoman":
            return _to_roman(n, upper=False)
        case "upperRoman":
            return _to_roman(n, upper=True)
        case "decimalZero":
            return f"{n:02d}"
        case _:
            return str(n)


class NumberingResolver:
    def __init__(self, document: DocxDocument) -> None:
        self._abstracts: dict[int, _Abstract] = {}
        self._nums: dict[int, tuple[int, dict[int, int]]] = {}  # numId -> (abstractId, overrides)
        self._counters: dict[int, dict[int, int]] = {}  # abstractId -> level -> current value
        self._started_nums: set[int] = set()
        try:
            root = document.part.numbering_part.element
        except (KeyError, NotImplementedError, AttributeError):
            return  # document has no numbering definitions
        for abstract in root.findall(qn("w:abstractNum")):
            abstract_id = _int_attr(abstract, "w:abstractNumId")
            if abstract_id is None:
                continue
            parsed = _Abstract()
            for lvl in abstract.findall(qn("w:lvl")):
                ilvl = _int_attr(lvl, "w:ilvl")
                if ilvl is None:
                    continue
                fmt_el, text_el = lvl.find(qn("w:numFmt")), lvl.find(qn("w:lvlText"))
                parsed.levels[ilvl] = _Level(
                    start=_int_attr(lvl.find(qn("w:start")), "w:val") or 1,
                    fmt=fmt_el.get(qn("w:val")) if fmt_el is not None else "decimal",
                    text=text_el.get(qn("w:val"), "") if text_el is not None else "",
                )
            self._abstracts[abstract_id] = parsed
        for num in root.findall(qn("w:num")):
            num_id = _int_attr(num, "w:numId")
            abstract_id = _int_attr(num.find(qn("w:abstractNumId")), "w:val")
            if num_id is None or abstract_id is None:
                continue
            overrides: dict[int, int] = {}
            for override in num.findall(qn("w:lvlOverride")):
                ilvl = _int_attr(override, "w:ilvl")
                start = _int_attr(override.find(qn("w:startOverride")), "w:val")
                if ilvl is not None and start is not None:
                    overrides[ilvl] = start
            self._nums[num_id] = (abstract_id, overrides)

    @staticmethod
    def _num_pr(paragraph_element, style) -> tuple[int | None, int | None]:  # type: ignore[no-untyped-def]
        """(numId, ilvl) from the paragraph, falling back through its style chain."""
        num_pr = paragraph_element.find(qn("w:pPr") + "/" + qn("w:numPr"))
        num_id = _int_attr(num_pr.find(qn("w:numId")) if num_pr is not None else None, "w:val")
        ilvl = _int_attr(num_pr.find(qn("w:ilvl")) if num_pr is not None else None, "w:val")
        while num_id is None and style is not None:
            style_pr = style.element.find(qn("w:pPr") + "/" + qn("w:numPr"))
            if style_pr is not None:
                num_id = _int_attr(style_pr.find(qn("w:numId")), "w:val")
                if ilvl is None:
                    ilvl = _int_attr(style_pr.find(qn("w:ilvl")), "w:val")
            style = style.base_style
        return num_id, ilvl

    def label_for(self, paragraph_element, style) -> tuple[str | None, int | None]:  # type: ignore[no-untyped-def]
        """Advance the counters for this paragraph and return (label, level). Label is None for
        unnumbered paragraphs and bullets."""
        num_id, ilvl = self._num_pr(paragraph_element, style)
        if not num_id or num_id not in self._nums:  # numId 0 explicitly removes numbering
            return None, None
        ilvl = min(max(ilvl or 0, 0), MAX_LEVELS - 1)
        abstract_id, overrides = self._nums[num_id]
        abstract = self._abstracts.get(abstract_id)
        if abstract is None:
            return None, None
        counters = self._counters.setdefault(abstract_id, {})
        if num_id not in self._started_nums:
            self._started_nums.add(num_id)
            for level, start in overrides.items():
                counters[level] = start - 1
                for deeper in range(level + 1, MAX_LEVELS):
                    counters.pop(deeper, None)

        level_def = abstract.levels.get(ilvl, _Level())
        counters[ilvl] = counters.get(ilvl, level_def.start - 1) + 1
        for deeper in range(ilvl + 1, MAX_LEVELS):
            counters.pop(deeper, None)  # deeper levels restart

        if level_def.fmt in ("bullet", "none"):
            return None, ilvl
        label = level_def.text
        for level in range(ilvl + 1):
            definition = abstract.levels.get(level, _Level())
            value = counters.get(level, definition.start)
            label = label.replace(f"%{level + 1}", format_number(value, definition.fmt))
        label = label.strip()
        return (label or None), ilvl
