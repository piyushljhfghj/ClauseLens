"""Declarative base shared by all ORM models.

The naming convention gives every constraint and index a predictable name, which keeps
Alembic autogenerated migrations stable and reviewable.
"""

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def sql_in(column: str, values: tuple[str, ...]) -> str:
    """SQL for a CHECK constraint restricting `column` to `values`.

    Text + CHECK instead of native Postgres ENUM types: adding a value later is a one-line
    migration rather than an `ALTER TYPE` dance.
    """
    return f"{column} IN ({', '.join(repr(v) for v in values)})"
